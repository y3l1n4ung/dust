#!/usr/bin/env python3
"""Strict analyzer pass for Dust-generated Dart output.

The normal analyzer path keeps generated files low-noise by excluding `.g.dart`
and preserving the generated `type=lint` file ignore. This script copies one
package into a temporary repo-shaped workspace, includes generated files in
analysis, removes `type=lint` from Dust-generated files, and runs the analyzer
there without mutating the real checkout.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


TYPE_LINT_IGNORE = "// ignore_for_file: type=lint"
GENERATED_MARKER = "// Generated by dust."


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Analyze Dust-generated output without broad type=lint suppression.",
    )
    parser.add_argument(
        "--package",
        type=Path,
        help="Package path relative to the repository root.",
    )
    parser.add_argument(
        "--tool",
        choices=("dart", "flutter"),
        default="dart",
        help="Analyzer tool to run for the copied package.",
    )
    parser.add_argument(
        "--self-test",
        action="store_true",
        help="Prove strict mode catches a lint hidden by type=lint.",
    )
    args = parser.parse_args()

    if args.self_test:
        return run_self_test()

    if args.package is None:
        parser.error("--package is required unless --self-test is set")

    repo = repo_root()
    package_rel = relative_to_repo(repo, args.package)
    package = repo / package_rel
    if not package.is_dir():
        print(f"error: package path does not exist: {package}", file=sys.stderr)
        return 2

    with tempfile.TemporaryDirectory(prefix="dust-strict-generated-") as temp:
        temp_root = Path(temp) / "repo"
        temp_root.mkdir()
        copied_package = copy_package(repo, temp_root, package_rel)
        write_strict_root_analysis_options(temp_root)
        link_runtime_packages(repo, temp_root)
        generated_count, stripped_count = strip_type_lint_ignores(copied_package)
        if generated_count == 0:
            print(
                f"error: no Dust-generated Dart files found under {package_rel}",
                file=sys.stderr,
            )
            return 2
        if stripped_count == 0:
            print(
                f"error: no {TYPE_LINT_IGNORE!r} lines found under {package_rel}",
                file=sys.stderr,
            )
            return 2

        run_checked(pub_get_command(args.tool), copied_package)
        run_checked(analyze_command(args.tool), copied_package)
        print(
            "strict generated analyze passed: "
            f"package={package_rel} generated={generated_count} "
            f"without_type_lint={stripped_count}",
        )
    return 0


def repo_root() -> Path:
    return Path(__file__).resolve().parents[1]


def relative_to_repo(repo: Path, package: Path) -> Path:
    resolved = package if package.is_absolute() else repo / package
    try:
        return resolved.resolve().relative_to(repo)
    except ValueError as error:
        raise SystemExit(f"error: package must be inside repo: {package}") from error


def copy_package(repo: Path, temp_root: Path, package_rel: Path) -> Path:
    source = repo / package_rel
    destination = temp_root / package_rel
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(
        source,
        destination,
        ignore=shutil.ignore_patterns(
            ".dart_tool",
            ".flutter-plugins",
            ".flutter-plugins-dependencies",
            ".plugin_symlinks",
            "build",
        ),
    )
    return destination


def write_strict_root_analysis_options(temp_root: Path) -> None:
    (temp_root / "analysis_options.yaml").write_text(
        "# Generated by scripts/strict_generated_analyze.py.\n"
        "# Includes Dust .g.dart files and removes type=lint in a temp copy.\n"
        "analyzer:\n"
        "  errors:\n"
        "    public_member_api_docs: ignore\n"
        "    inference_failure_on_function_invocation: ignore\n"
        "    inference_failure_on_instance_creation: ignore\n"
        "    strict_raw_type: ignore\n",
    )


def link_runtime_packages(repo: Path, temp_root: Path) -> None:
    packages = temp_root / "packages"
    packages.symlink_to(repo / "packages", target_is_directory=True)


def strip_type_lint_ignores(package: Path) -> tuple[int, int]:
    generated_count = 0
    stripped_count = 0
    for path in sorted(package.rglob("*.dart")):
        if any(part in {".dart_tool", "build"} for part in path.parts):
            continue
        source = path.read_text()
        if GENERATED_MARKER not in source:
            continue
        generated_count += 1
        lines = source.splitlines()
        filtered = [line for line in lines if line != TYPE_LINT_IGNORE]
        if len(filtered) != len(lines):
            stripped_count += 1
            path.write_text("\n".join(filtered) + "\n")
    return generated_count, stripped_count


def pub_get_command(tool: str) -> list[str]:
    if tool == "flutter":
        return ["flutter", "pub", "get"]
    return ["dart", "pub", "get"]


def analyze_command(tool: str) -> list[str]:
    if tool == "flutter":
        return ["dart", "analyze", "--fatal-warnings"]
    return ["dart", "analyze", "--fatal-warnings"]


def run_checked(command: list[str], cwd: Path) -> None:
    print(f"==> ({cwd}) {' '.join(command)}")
    subprocess.run(command, cwd=cwd, check=True)


def run_self_test() -> int:
    with tempfile.TemporaryDirectory(prefix="dust-strict-generated-self-test-") as temp:
        package = Path(temp) / "hidden_lint_app"
        (package / "lib").mkdir(parents=True)
        (package / "pubspec.yaml").write_text(
            "name: hidden_lint_app\n"
            "publish_to: none\n"
            "environment:\n"
            '  sdk: ">=3.6.0 <4.0.0"\n',
        )
        (package / "analysis_options.yaml").write_text(
            "linter:\n"
            "  rules:\n"
            "    avoid_print: true\n",
        )
        generated = package / "lib" / "hidden.g.dart"
        generated.write_text(
            "// GENERATED CODE - DO NOT MODIFY BY HAND\n"
            f"{TYPE_LINT_IGNORE}\n"
            f"{GENERATED_MARKER}\n"
            "\n"
            "void hiddenLint() {\n"
            "  print('hidden by type=lint');\n"
            "}\n",
        )

        normal = subprocess.run(
            ["dart", "analyze", "--fatal-infos"],
            cwd=package,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            check=False,
        )
        if normal.returncode != 0:
            print(normal.stdout, file=sys.stderr)
            print("error: self-test normal analyzer path should pass", file=sys.stderr)
            return 1

        _, stripped_count = strip_type_lint_ignores(package)
        if stripped_count != 1:
            print("error: self-test did not strip type=lint", file=sys.stderr)
            return 1

        strict = subprocess.run(
            ["dart", "analyze", "--fatal-infos"],
            cwd=package,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            check=False,
        )
        if strict.returncode == 0 or "avoid_print" not in strict.stdout:
            print(strict.stdout, file=sys.stderr)
            print("error: self-test strict analyzer path should fail", file=sys.stderr)
            return 1
    print("strict generated analyze self-test passed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
